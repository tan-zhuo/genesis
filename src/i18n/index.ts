// Lightweight bilingual (English / 中文) i18n.
// UI chrome is translated via this dictionary; simulation-generated event text
// is stored bilingually inside each WorldEvent at generation time (so replay
// determinism is untouched by the display language).
import { create } from 'zustand';

export type Lang = 'en' | 'zh';

interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('civsim.lang');
    if (saved === 'en' || saved === 'zh') return saved;
    return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
  } catch {
    return 'en';
  }
}

export const useI18nStore = create<I18nState>((set) => ({
  lang: typeof window !== 'undefined' ? initialLang() : 'en',
  setLang: (l) => {
    try {
      localStorage.setItem('civsim.lang', l);
    } catch {
      /* ignore */
    }
    set({ lang: l });
  },
}));

